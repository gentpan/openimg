const BASE = "";

async function jfetch<T>(path: string, opts: RequestInit = {}): Promise<T> {
  // FormData must set its own Content-Type: the multipart boundary is
  // generated by the browser, and forcing application/json here makes the
  // server parse the body as JSON and reject every file upload.
  const isForm = opts.body instanceof FormData;
  // Accept-Language on every call, so a rejection comes back in the language
  // the page is already in. Without it an English UI shows Chinese errors,
  // which reads worse than an untranslated interface — the error is exactly
  // the moment the reader needs to understand.
  const lang = currentLang() === "zh" ? "zh-CN" : "en";
  // The brand hint lets the server render emails (OTP codes) in the theme the
  // person is actually looking at. It is a hint, not state: the server clamps
  // unknown values and defaults to green.
  const brand = currentBrand();
  const r = await fetch(BASE + path, {
    credentials: "include",
    headers: isForm
      ? { "Accept-Language": lang, "X-Openimg-Brand": brand, ...(opts.headers || {}) }
      : { "Content-Type": "application/json", "Accept-Language": lang, "X-Openimg-Brand": brand, ...(opts.headers || {}) },
    ...opts,
  });
  if (!r.ok) {
    let msg = `${r.status} ${r.statusText}`;
    try {
      const body = await r.json();
      if (body?.error) msg = body.error;
    } catch {}
    throw new Error(msg);
  }
  if (r.status === 204) return undefined as T;
  return r.json();
}

