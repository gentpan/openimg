export const imageApi = {
  publicStats: () => jfetch<PublicStats>("/api/public-stats"),

  /**
   * Uploads one file. Progress is reported through XHR rather than fetch
   * because fetch still has no upload-progress event, and a picture host
   * without a progress bar feels broken on anything slower than a LAN.
   */
  /**
   * 按网址取图。**服务端下载**,不是浏览器下载。
   *
   * 浏览器这条路走不通:第三方图片地址基本都会被 CORS 挡掉,而能绕过 CORS 的
   * 只有服务端。代价是这个接口让任何登录用户都能驱使我们的服务器去请求一个
   * 地址,防护全在后端的 fetchurl 包里。
   *
   * 没有进度:字节从来没有经过浏览器,进度只有服务端知道。与其编一个假的百分
   * 比,不如在界面上就显示成"正在取"。
   */
  uploadFromURL(url: string): Promise<UploadResult> {
    return jfetch("/api/upload/from-url", {
      method: "POST",
      body: JSON.stringify({ url }),
    });
  },

  upload(
    file: File,
    opts: { onProgress?: (pct: number) => void; signal?: AbortSignal } = {},
  ): Promise<UploadResult> {
    return new Promise((resolve, reject) => {
      const form = new FormData();
      form.append("file", file);

      const xhr = new XMLHttpRequest();
      xhr.open("POST", BASE + "/api/upload");
      // The fetch wrapper above is not on this path: uploads go through XHR
      // for byte-level progress, so the header has to be set again here. This
      // is where "file too large" and "format not allowed" come back.
      xhr.setRequestHeader("Accept-Language", currentLang() === "zh" ? "zh-CN" : "en");
      xhr.setRequestHeader("X-Openimg-Brand", currentBrand());
      xhr.withCredentials = true;

      xhr.upload.onprogress = (e) => {
        if (e.lengthComputable && opts.onProgress) {
          opts.onProgress(Math.round((e.loaded / e.total) * 100));
        }
      };
      xhr.onload = () => {
        let body: any = null;
        try {
          body = JSON.parse(xhr.responseText);
        } catch {}
        if (xhr.status >= 200 && xhr.status < 300) resolve(body);
        else reject(new Error(body?.error || `${xhr.status} ${xhr.statusText}`));
      };
      xhr.onerror = () => reject(new Error(dicts[currentLang()].upload.networkError));
      xhr.onabort = () => reject(new Error(dicts[currentLang()].common.cancelled));
      opts.signal?.addEventListener("abort", () => xhr.abort());

      xhr.send(form);
    });
  },

  list: (params: { limit?: number; offset?: number; q?: string; sort?: SortKey } = {}) => {
    const qs = new URLSearchParams();
    if (params.limit) qs.set("limit", String(params.limit));
    if (params.offset) qs.set("offset", String(params.offset));
    if (params.q) qs.set("q", params.q);
    if (params.sort) qs.set("sort", params.sort);
    return jfetch<{ images: Image[] | null; total: number; limit: number; offset: number }>(
      "/api/images?" + qs.toString(),
    ).then((r) => ({ ...r, images: r.images ?? [] }));
  },
  remove: (id: string) => jfetch<{ ok: true }>(`/api/images/${id}`, { method: "DELETE" }),
  /**
   * Deletes many at once. `all: true` takes everything matching `q` rather
   * than the listed ids; the server caps each call, so keep calling while
   * `remaining` is above zero.
   */
  bulkRemove: (body: { ids?: string[]; all?: boolean; q?: string; code?: string }) =>
    jfetch<{ ok: true; deleted: number; remaining: number }>("/api/images/bulk-delete", {
      method: "POST",
      body: JSON.stringify(body),
    }),
  /** Renders one display size on demand. Idempotent — asking twice is free. */
  makeVariant: (id: string, width: 200 | 600 | 1200) =>
    jfetch<{ ok: true; variant: string; url: string; existing?: boolean; bytes?: number }>(
      `/api/images/${id}/variant`,
      { method: "POST", body: JSON.stringify({ width }) },
    ),
};

// ----- AI image generation -----
/**
 * Text to image. Three calls, and the middle one does not wait for a picture:
 * generation takes tens of seconds, so `generate` returns as soon as the task
 * is accepted and `generations` is polled until that record turns terminal.
 *
 * The completed record carries an `image_id` into the `images` map, whose
 * entries are the same `Image` objects the gallery lists — a generated picture
 * is an ordinary upload from the moment it lands.
 */
export const aiApi = {
  /** `{enabled: false}` on a deployment with no upstream key configured. */
  status: () => jfetch<AIStatus>("/api/ai/status"),
  generate: (prompt: string, size: string, resolution: string) =>
    jfetch<{ generation: AIGeneration }>("/api/ai/generate", {
      method: "POST",
      body: JSON.stringify({ prompt, size, resolution }),
    }).then((r) => r.generation),
  /**
   * Retouching: the same submission, given one to four pictures to work from.
   *
   * The ids are the user's own images and the server resolves them to their
   * public CDN URLs before calling upstream — nothing is uploaded again, and
   * nothing is base64'd, because the files are already on a public origin the
   * model can fetch for itself.
   *
   * `size` and `resolution` are genuinely optional here: omit the size and the
   * output keeps the shape of the picture that went in, which is what someone
   * removing a watermark almost always wants.
   */
  edit: (prompt: string, imageIds: string[], size?: string | null, resolution?: string | null) =>
    jfetch<{ generation: AIGeneration }>("/api/ai/edit", {
      method: "POST",
      body: JSON.stringify({
        prompt,
        image_ids: imageIds,
        ...(size ? { size } : {}),
        ...(resolution ? { resolution } : {}),
      }),
    }).then((r) => r.generation),
  /** Newest first, capped server-side. Both members can come back null.
   *  Carries generations and edits alike; the pages filter by `kind`. */
  /** 从列表里删掉一条记录。alsoImage 时连产出图一起删。
   *  服务端只是把它标成隐藏——行是日限的计数单位,真删等于退回当天配额。 */
  deleteGeneration: (id: string, alsoImage: boolean) =>
    jfetch<{ ok: true; image_deleted: boolean }>(
      `/api/ai/generations/${id}${alsoImage ? "?image=1" : ""}`,
      { method: "DELETE" },
    ),
  generations: () =>
    jfetch<{ generations: AIGeneration[] | null; images: Record<string, Image> | null }>(
      "/api/ai/generations",
    ).then((r) => ({ generations: r.generations ?? [], images: r.images ?? {} })),
};

